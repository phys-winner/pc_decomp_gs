"""Generate compact native data for every effect used by Grief Syndrome."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORACLE = ROOT / "build/effect-oracle"
OUT = ROOT / "app/native/host"
EFFECTS = [
    ("export", 26640, "6a84082c677abdb1e29b2316931b2a5a0d4425f7551205fe02e67048b533be0a"),
    ("export-63f418", 48904, None),
    ("export-64b320", 43988, None),
    ("export-655ef8", 12432, None),
    ("export-639380", 24724, None),
]
UNSUPPORTED = 3131951870


def c_string(value):
    return "NULL" if value is None else json.dumps(value)


def changed(manifest, pass_data):
    baseline = manifest["baseline"]
    state = pass_data["state"]
    entries = []
    for key, value in state["render_states"].items():
        if value != UNSUPPORTED and baseline["render_states"].get(key) != value:
            entries.append((0, int(key), 0, value))
    for key, value in state["texture_stage_states"].items():
        if value != UNSUPPORTED and baseline["texture_stage_states"].get(key) != value:
            stage, kind = map(int, key.split(":"))
            entries.append((1, stage, kind, value))
    for key, value in state["sampler_states"].items():
        if value != UNSUPPORTED and baseline["sampler_states"].get(key) != value:
            stage, kind = map(int, key.split(":"))
            entries.append((2, stage, kind, value))
    if state.get("fvf", 0) != baseline.get("fvf", 0):
        entries.append((3, 0, 0, state["fvf"]))
    return entries


def main():
    manifests = []
    blobs = []
    indices = {}
    for effect, (directory, size, source_hash) in enumerate(EFFECTS):
        manifest = json.loads((ORACLE / directory / "effect-manifest.json").read_text(encoding="utf-8"))
        manifests.append(manifest)
        for technique in manifest["items"]:
            for pass_index, pass_data in enumerate(technique["pass_items"]):
                for kind in ("vs", "ps"):
                    path = ORACLE / directory / f"t{technique['index']}p{pass_index}_{kind}.bin"
                    if not path.exists():
                        continue
                    data = path.read_bytes()
                    digest = hashlib.sha256(data).hexdigest()
                    if digest not in indices:
                        indices[digest] = len(blobs)
                        blobs.append((digest, data))

    lines = ["/* Generated by tools/generate_effect_runtime.py from Microsoft-D3DX oracle exports. */",
             '#include "effect_data.h"', ""]
    for index, (digest, data) in enumerate(blobs):
        lines.append(f"static const uint8_t fx_blob_{index}[] = {{")
        for start in range(0, len(data), 12):
            lines.append("    " + ",".join(f"0x{value:02X}" for value in data[start:start + 12]) + ",")
        lines += ["};", f"/* {digest} */", ""]
    lines.append("const fx_blob fx_blobs[] = {")
    for index, (digest, data) in enumerate(blobs):
        lines.append(f"    {{fx_blob_{index}, {len(data)}u}},")
    lines += ["};", f"const uint32_t fx_blob_count = {len(blobs)}u;", ""]

    for effect, manifest in enumerate(manifests):
        for technique in manifest["items"]:
            for pass_index, pass_data in enumerate(technique["pass_items"]):
                entries = changed(manifest, pass_data)
                lines.append(f"static const fx_state_change fx_states_{effect}_{technique['index']}_{pass_index}[] = {{")
                for kind, first, second, value in entries:
                    lines.append(f"    {{{kind}u, {first}u, {second}u, {value}u}},")
                if not entries:
                    lines.append("    {255u, 0u, 0u, 0u},")
                lines += ["};", ""]

    for effect, manifest in enumerate(manifests):
        for technique in manifest["items"]:
            lines.append(f"static const fx_pass fx_passes_{effect}_{technique['index']}[] = {{")
            for pass_index, pass_data in enumerate(technique["pass_items"]):
                directory = EFFECTS[effect][0]
                vs_path = ORACLE / directory / f"t{technique['index']}p{pass_index}_vs.bin"
                ps_path = ORACLE / directory / f"t{technique['index']}p{pass_index}_ps.bin"
                vs = indices.get(hashlib.sha256(vs_path.read_bytes()).hexdigest(), -1) if vs_path.exists() else -1
                ps = indices.get(hashlib.sha256(ps_path.read_bytes()).hexdigest(), -1) if ps_path.exists() else -1
                state_name = f"fx_states_{effect}_{technique['index']}_{pass_index}"
                lines.append(f"    {{{c_string(pass_data['name'])}, {vs}, {ps}, {state_name}, {len(changed(manifest, pass_data))}u}},")
            lines += ["};", ""]

    all_params = [parameter for manifest in manifests for parameter in manifest["parameter_items"]]
    lines.append("const fx_param_desc fx_params[] = {")
    for parameter in all_params:
        semantic = None if parameter.get("semantic_null") else parameter["semantic"]
        lines.append(f"    {{{c_string(parameter['name'])}, {c_string(semantic)}, "
                     f"{parameter['class']}u, {parameter['type']}u, {parameter['rows']}u, "
                     f"{parameter['columns']}u, {parameter['elements']}u}},")
    lines += ["};", f"const uint32_t fx_param_count = {len(all_params)}u;", ""]

    lines.append("const fx_technique fx_techniques[] = {")
    pass_offset = 0
    for effect, manifest in enumerate(manifests):
        for technique in manifest["items"]:
            lines.append(f"    {{{c_string(technique['name'])}, fx_passes_{effect}_{technique['index']}, "
                         f"{pass_offset}u, {technique['passes']}u}},")
            pass_offset += technique["passes"]
    lines += ["};", f"const uint32_t fx_technique_count = {pass_offset and sum(len(manifest['items']) for manifest in manifests)}u;", ""]

    lines.append("const fx_effect_def fx_effects[] = {")
    technique_offset = 0
    parameter_offset = 0
    for effect, ((directory, size, source_hash), manifest) in enumerate(zip(EFFECTS, manifests)):
        pass_count = sum(technique["passes"] for technique in manifest["items"])
        lines.append(f"    {{{size}u, {technique_offset}u, {len(manifest['items'])}u, "
                     f"{parameter_offset}u, {len(manifest['parameter_items'])}u, {pass_count}u}},")
        if source_hash:
            lines.append(f"/* Source SHA-256: {source_hash} */")
        technique_offset += len(manifest["items"])
        parameter_offset += len(manifest["parameter_items"])
    lines += ["};", f"const uint32_t fx_effect_def_count = {len(manifests)}u;", ""]
    (OUT / "effect_data.c").write_text("\n".join(lines), encoding="utf-8")
    (OUT / "effect_data.h").write_text("""#ifndef GRIEF_EFFECT_DATA_H
#define GRIEF_EFFECT_DATA_H
#include <stdint.h>

typedef struct { const uint8_t *data; uint32_t size; } fx_blob;
typedef struct { uint8_t kind; uint16_t first, second; uint32_t value; } fx_state_change;
typedef struct { const char *name, *semantic; uint16_t cls, type, rows, columns, elements; } fx_param_desc;
typedef struct { const char *name; int vs, ps; const fx_state_change *states; uint32_t state_count; } fx_pass;
typedef struct { const char *name; const fx_pass *passes; uint32_t first_pass, pass_count; } fx_technique;
typedef struct { uint32_t size, first_technique, technique_count, first_param, param_count, pass_count; } fx_effect_def;
extern const fx_blob fx_blobs[];
extern const uint32_t fx_blob_count;
extern const fx_param_desc fx_params[];
extern const uint32_t fx_param_count;
extern const fx_technique fx_techniques[];
extern const uint32_t fx_technique_count;
extern const fx_effect_def fx_effects[];
extern const uint32_t fx_effect_def_count;
#endif
""", encoding="utf-8")
    print(f"Generated {len(blobs)} unique shaders, {technique_offset} techniques, {parameter_offset} parameters, {pass_offset} passes")


if __name__ == "__main__":
    main()
