"""Generate the embedded Windows CP932 conversion table using Python's codec."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app/native/host/cp932_table.inc"

single = []
for value in range(0x80, 0x100):
    try:
        decoded = bytes([value]).decode("cp932")
        single.append(ord(decoded) if len(decoded) == 1 else 0xFFFD)
    except UnicodeDecodeError:
        single.append(0xFFFD)

pairs = []
for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
    for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
        try:
            decoded = bytes([lead, trail]).decode("cp932")
        except UnicodeDecodeError:
            continue
        if len(decoded) == 1:
            pairs.append(((lead << 8) | trail, ord(decoded)))

lines = ["/* Generated by tools/generate_cp932.py from Python cp932. */",
         "static const uint16_t cp932_single[128] = {"]
for start in range(0, 128, 12):
    lines.append("    " + ",".join(f"0x{value:04X}" for value in single[start:start + 12]) + ",")
lines += ["};", "", "static const cp932_pair cp932_pairs[] = {"]
for key, value in pairs:
    lines.append(f"    {{0x{key:04X}u, 0x{value:04X}u}},")
lines += ["};", f"static const uint32_t cp932_pair_count = {len(pairs)}u;", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(pairs)} double-byte mappings written to {OUT}")
